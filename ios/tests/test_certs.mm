id CreateCert(std::string cert) {
  CFDataRef cfData = CFDataCreate(
      kCFAllocatorDefault, reinterpret_cast<const UInt8*>(cert.data()),
      cert.size());
  SecCertificateRef result =
      SecCertificateCreateWithData(kCFAllocatorDefault, cfData);
  CFRelease(cfData);
  return CFBridgingRelease(result);
}

id CreateTrust(std::string leaf, bool use_modern_subroot) {
  id sub_root = use_modern_subroot
                    ? CreateCert(std::string(std::begin(kSubRootCA2),
                                             std::end(kSubRootCA2)))
                    : CreateCert(std::string(std::begin(kSubRootCA1),
                                             std::end(kSubRootCA1)));
  NSArray *chain = @[
    CreateCert(leaf), sub_root,
    CreateCert(std::string(std::begin(kRootCA), std::end(kRootCA)))
  ];
  NSArray *policies = @[ (id)CFBridgingRelease(SecPolicyCreateBasicX509()) ];

  SecTrustRef result = nullptr;
  SecTrustCreateWithCertificates((CFTypeRef)chain, (CFTypeRef)policies,
                                 &result);
  assert(result);
  return CFBridgingRelease(result);
}

